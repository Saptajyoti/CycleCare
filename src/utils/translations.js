export function translateSelfCare(language, type, id, index) {
  if (language !== "hi") return null;
  if (type === "ui") return selfCareHindi.ui[id];
  if (type === "category") return selfCareHindi.categories[id]?.[index];
  if (type === "suggestion") return selfCareHindi.suggestions[id]?.[index];
  return null;
}

